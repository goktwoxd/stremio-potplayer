#!/usr/bin/env python3
"""Regenerate or check extension/labels.js from Stremio/stremio-translations.

Usage:
    python tools/update-labels.py
    python tools/update-labels.py --source C:\\path\\to\\stremio-translations
    python tools/update-labels.py --check

Without --source, the script lists the repository through the GitHub API and
downloads each locale file. With --source, it reads a local clone instead.

The generated list keeps historical labels as well as current ones: Stremio Web
can run against an older translation snapshot, so an old label must not stop
matching when a locale is reworded upstream.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

KEY = "CTX_COPY_STREAM_LINK"
API_URL = "https://api.github.com/repos/Stremio/stremio-translations/contents/"
FALLBACK_LABEL = "copy stream link"

# Labels that appeared in Stremio Web releases but are no longer in the latest
# translation files. Keep them so older deployments still match.
LEGACY_LABELS = {
    "copier le lien du stream",
    "copia il link dello stream",
    "copiar link de transmissão",
    "kopier stream link",
    "sao chép liên kết luồng",
    "adatfolyam hivatkozásának másolása",
}

OUTPUT = Path(__file__).resolve().parent.parent / "extension" / "labels.js"


def fetch_json(url: str):
    request = urllib.request.Request(
        url,
        headers={"User-Agent": "stremio-potplayer-label-updater"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def labels_from_source(source: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for path in sorted(source.glob("*.json")):
        if path.name.startswith("package"):
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except Exception as exc:  # noqa: BLE001 - report and keep going
            print(f"skip {path.name}: {exc}", file=sys.stderr)
            continue
        value = data.get(KEY)
        if isinstance(value, str) and value.strip():
            values[path.name] = value.strip()
    return values


def labels_from_github() -> dict[str, str]:
    values: dict[str, str] = {}
    for entry in fetch_json(API_URL):
        name = entry.get("name", "")
        if not name.endswith(".json") or name.startswith("package"):
            continue
        download_url = entry.get("download_url")
        if not download_url:
            continue
        try:
            data = fetch_json(download_url)
        except Exception as exc:  # noqa: BLE001 - one bad locale must not abort
            print(f"skip {name}: {exc}", file=sys.stderr)
            continue
        value = data.get(KEY)
        if isinstance(value, str) and value.strip():
            values[name] = value.strip()
    return values


def normalize(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip().lower()


def existing_labels() -> set[str]:
    """Read labels from the current generated file, if it exists."""
    if not OUTPUT.exists():
        return set()

    labels: set[str] = set()
    for line in OUTPUT.read_text(encoding="utf-8").splitlines():
        candidate = line.strip().rstrip(",")
        if candidate.startswith('"') and candidate.endswith('"'):
            try:
                labels.add(json.loads(candidate))
            except json.JSONDecodeError:
                pass
    return labels


def build(values: dict[str, str]) -> tuple[str, list[str]]:
    raw = {normalize(value) for value in values.values()}
    raw.update(normalize(label) for label in LEGACY_LABELS)
    raw.update(normalize(label) for label in existing_labels())

    unique = sorted(label for label in raw if label)
    if FALLBACK_LABEL in unique:
        unique.remove(FALLBACK_LABEL)
    unique.insert(0, FALLBACK_LABEL)

    lines = [
        "/* Generated by tools/update-labels.py from Stremio/stremio-translations.",
        f" * {len(values)} locales, {len(unique)} labels (including historical labels).",
        " * Do not edit by hand. */",
        "globalThis.__STREMIO_POTPLAYER_COPY_LABELS__ = [",
    ]
    lines.extend(f"  {json.dumps(label, ensure_ascii=False)}," for label in unique)
    lines.append("];")
    return "\n".join(lines) + "\n", unique


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        type=Path,
        help="local clone of Stremio/stremio-translations (skips network)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if extension/labels.js is out of date instead of writing it",
    )
    args = parser.parse_args()

    if args.source:
        values = labels_from_source(args.source)
    else:
        values = labels_from_github()

    if not values:
        print("No labels found. Check --source or your network connection.", file=sys.stderr)
        return 1

    text, unique = build(values)

    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current == text:
            print("labels.js is up to date")
            return 0

        old = {normalize(label) for label in existing_labels()}
        new = set(unique)
        for label in sorted(new - old):
            print(f"add: {label}", file=sys.stderr)
        for label in sorted(old - new):
            print(f"remove: {label}", file=sys.stderr)
        print(
            "labels.js is out of date; run tools/update-labels.py and commit the result.",
            file=sys.stderr,
        )
        return 1

    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(values)} locales, {len(unique)} labels)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
